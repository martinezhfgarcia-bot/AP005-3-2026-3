# Se realiza primero la operación matemática de suma (7 + 8 = 15) y luego se 
# evalúa lógicamente si ese resultado es exactamente igual (==) a 11. 
# Como 15 no es igual a 11, el resultado de la expresión es el valor booleano 
# 'False' (Falso). Este valor se asigna a la variable 'my_cool_variable'.
my_cool_variable = 7 + 8 == 11

# Imprime en la consola el contenido almacenado en la variable, 
# por lo que mostrará la palabra 'False' en la pantalla.
print(my_cool_variable)
